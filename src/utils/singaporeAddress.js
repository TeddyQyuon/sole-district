const addressCache = new Map();

/**
 * Validates whether a value is a valid 6-digit Singapore postal code.
 */
export function isValidSingaporePostal(value) {
  return /^[0-9]{6}$/.test(String(value || '').trim());
}

/**
 * Normalizes title casing for road and building names.
 */
function toTitleCase(str) {
  if (!str) return '';
  return str
    .toLowerCase()
    .split(' ')
    .map((word) => {
      if (['hdb', 'ion', 'mbs', 'dsm', 'dbs', 'ocbc', 'uob', 'sg'].includes(word)) return word.toUpperCase();
      return word.charAt(0).toUpperCase() + word.slice(1);
    })
    .join(' ');
}

/**
 * Searches Singapore addresses via OneMap API with in-memory caching
 * and resilient postal district fallback.
 */
export async function searchSingaporeAddress(query) {
  const clean = String(query || '').trim();
  if (!clean || clean.length < 2) return [];

  const cacheKey = clean.toUpperCase();
  if (addressCache.has(cacheKey)) {
    return addressCache.get(cacheKey);
  }

  try {
    const url = `https://www.onemap.gov.sg/api/common/elastic/search?searchVal=${encodeURIComponent(clean)}&returnGeom=N&getAddrDetails=Y`;
    const response = await fetch(url, { headers: { Accept: 'application/json' } });
    if (response.ok) {
      const data = await response.json();
      if (Array.isArray(data?.results) && data.results.length > 0) {
        const results = data.results.slice(0, 6).map((item) => {
          const blk = item.BLK_NO && item.BLK_NO !== 'NIL' ? `Blk ${item.BLK_NO} ` : '';
          const road = toTitleCase(item.ROAD_NAME || '');
          const building = item.BUILDING && item.BUILDING !== 'NIL' ? toTitleCase(item.BUILDING) : '';
          const postal = item.POSTAL && item.POSTAL !== 'NIL' ? item.POSTAL : clean.length === 6 ? clean : '';

          let line1 = `${blk}${road}`.trim();
          if (!line1 && building) line1 = building;

          return {
            searchVal: item.SEARCHVAL,
            blockNo: item.BLK_NO !== 'NIL' ? item.BLK_NO : '',
            roadName: road,
            building,
            postalCode: postal,
            line1: line1 || toTitleCase(item.ADDRESS || clean),
            label: building && building !== road
              ? `${building} · ${line1} (S${postal})`
              : `${line1}${postal ? ` (S${postal})` : ''}`,
            source: 'onemap',
          };
        });
        addressCache.set(cacheKey, results);
        return results;
      }
    }
  } catch (err) {
    console.warn('OneMap search lookup bypassed:', err.message);
  }

  // Fallback: If 6-digit postal code, resolve using Singapore postal district dictionary
  if (isValidSingaporePostal(clean)) {
    const sector = clean.slice(0, 2);
    const districtInfo = POSTAL_DISTRICTS[sector];
    const fallbackResult = [{
      searchVal: clean,
      blockNo: '',
      roadName: '',
      building: '',
      postalCode: clean,
      line1: districtInfo ? `${districtInfo.area}` : 'Singapore',
      label: districtInfo ? `${districtInfo.area} · District ${districtInfo.district} (S${clean})` : `Singapore ${clean}`,
      source: 'district_lookup',
    }];
    addressCache.set(cacheKey, fallbackResult);
    return fallbackResult;
  }

  return [];
}

/**
 * Formats a full Singapore shipping address for display or labels.
 */
export function formatSingaporeShipping(address) {
  if (!address) return '';
  const parts = [];
  if (address.recipient) parts.push(address.recipient);
  if (address.phone) parts.push(`(${address.phone})`);
  const addrParts = [];
  if (address.line1) addrParts.push(address.line1);
  if (address.line2) addrParts.push(address.line2);
  if (address.postal_code) addrParts.push(`Singapore ${address.postal_code}`);
  if (addrParts.length) parts.push(addrParts.join(', '));
  return parts.join(' · ');
}
